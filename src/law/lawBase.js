export const lawKey = (n) => String(n || "").replace(/\s+/g, "");

/** 서버 목록 → 기준선보다 늦은 개정 / 새 기준 */
export function lawChanges(items, base = LAW_BASE) {
  const out = [];
  const seen = new Set();
  for (const it of items || []) {
    const k = lawKey(it.n);
    if (!k || seen.has(k)) continue;
    seen.add(k);
    const b = base[k];
    if (!b) out.push({ ...it, kind: "new" });
    else if (it.eff && it.eff > b) out.push({ ...it, kind: "amend", base: b });
  }
  return out.sort((a, b) => (b.eff || "").localeCompare(a.eff || ""));
}
