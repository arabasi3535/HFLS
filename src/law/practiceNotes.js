import { num } from "./logic";

/**
 * @param rv review() 결과
 * @param mode "new" | "existing"
 * @returns [{ id, title, text, basis }]
 */
export function practiceNotes(rv, mode) {
  if (!rv) return [];
  const u = rv.use;
  const g = (...ks) => ks.some((k) => u.g.includes(k));
  const inp = rv.input || {};
  const date = inp.action && inp.action !== "new" && inp.date2 ? inp.date2 : inp.date;
  const out = [];

  // 교육시설법 제10조의3 — 2025.2.7. 시행(법률 제20437호 부칙: 시행 후 감독청 승인·신고 또는 건축허가 신청·건축신고분부터)
  if (date && date >= "2025-02-07" && g("kinder", "edu_dorm", "school") && (inp.action === "new" || inp.action === "extension" || !inp.action)) {
    out.push({
      id: "edu-law",
      title: "교육시설법 — 스프링클러설비 또는 간이스프링클러설비 설치 의무(타법)",
      text: `${g("kinder") ? "유치원을" : g("edu_dorm") ? "학교 기숙사·합숙소를" : "특수학교(해당하는 경우)·학교 기숙사·합숙소·임시교실을"} 신설(신축·증축·개축·재축·이전)하는 경우 「소방시설법」 제12조제1항(별표4)과 별개로 스프링클러설비 또는 간이스프링클러설비 등을 설치해야 합니다. 설비 종류·범위는 같은 법 시행령 확인 필요.`,
      basis: "「교육시설 등의 안전 및 유지관리 등에 관한 법률」 제10조의3(2025.2.7. 시행) — 경북 2024.10.15. 개정사항 알림",
    });
  }

  // 연립·다세대 필로티 주차장 — 주택전용 간이스프링클러설비 헤드 제외 가능
  if (date && date >= "2024-12-01" && g("row", "multi")) {
    out.push({
      id: "row-piloti",
      title: "연립·다세대 필로티 주차장 — 주택전용 간이스프링클러설비 헤드",
      text: "주택전용 간이스프링클러설비는 세대 내 화재 대응 설비로, 직접 외기에 개방된 소규모 필로티 주차장 부분은 헤드 설치를 제외하고 세대 내부에만 설치할 수 있습니다(NFTC 103 2.12.1.1 헤드 제외 장소). 50세대 이상이면 내부 차고·주차장 물분무등소화설비 기준을 따로 확인하십시오.",
      basis: "소방청 질의회신(2025.7.29. 연찬 자료)",
    });
  }

  // 단지형 다세대주택(주택법) 5층 — 아파트 아님
  const gf = num(inp.gf);
  if (g("apt") && gf !== null && gf === 5) {
    out.push({
      id: "danji-multi",
      title: "주택으로 쓰는 층수 5층 — 단지형 다세대주택인지 확인",
      text: "「주택법」에 따른 단지형 다세대주택(건축위원회 심의로 주택 층수 5층까지 허용)은 5층이라도 아파트가 아니라 다세대주택입니다 — 해당하면 용도를 다세대주택으로 바꾸어 판정하십시오.",
      basis: "법제처 법령해석(2013.7.22., 법령해석총괄과-2502) — 2013.11. 소방청 시달",
    });
  }

  // 자동화재속보설비 — 2022.12.1. 대상 축소 → 기존 설치분 철거 가능
  if (mode === "existing" && Array.isArray(rv.compare)) {
    const rep = rv.compare.find((c) => c.fac.key === "report");
    if (rep && rep.kind === "removed") {
      out.push({
        id: "report-remove",
        title: "자동화재속보설비 — 현행 설치 대상 아님(철거 가능)",
        text: "2022.12.1. 개정으로 업무시설·공장·창고·국방군사·발전시설(1,500㎡ 층)·30층 이상·전기저장시설이 속보설비 대상에서 빠졌습니다. 현행 기준 대상이 아니면 신법 우선 원칙에 따라 철거 가능 — 관계인이 정비신청서를 제출하면 소방서 검토(5일) 후 통보, 철거는 수신기 결선 분리가 아니라 설비 전체를 철거하고 10일 이내 완료 통보(의무 아님, 안내 사항).",
        basis: "소방청 「자동화재속보설비 설치대상 변경 관련 업무처리 지침」(2023.11.21., 소방분석제도과)",
      });
    }
  }

  return out;
}
