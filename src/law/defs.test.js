import { parseDefArticle, defsFromFam, defsFromStd, searchDefs } from "./defs";

// 법제처 현행 원문(2026.11.24. /api/lawat 응답에서 발췌)
const FIRE = `제2조(정의)
① 이 법에서 사용하는 용어의 뜻은 다음과 같다.
1. "소방시설"이란 소화설비, 경보설비, 피난구조설비, 소화용수설비, 그 밖에 소화활동설비로서 대통령령으로 정하는 것을 말한다.
2. "소방시설등"이란 소방시설과 비상구(非常口), 그 밖에 소방 관련 시설로서 대통령령으로 정하는 것을 말한다.
6. "화재안전기준"이란 소방시설 설치 및 관리를 위한 다음 각 목의 기준을 말한다.
가. 성능기준: 화재안전 확보를 위하여 재료, 공간 및 설비 등에 요구되는 안전성능으로서 소방청장이 고시로 정하는 기준
나. 기술기준: 가목에 따른 성능기준을 충족하는 상세한 규격, 특정한 수치 및 시험방법 등에 관한 기준으로서 행정안전부령으로 정하는 절차에 따라 소방청장의 승인을 받은 기준
7. "소방용품"이란 소방시설등을 구성하거나 소방용으로 사용되는 제품 또는 기기로서 대통령령으로 정하는 것을 말한다.
② 이 법에서 사용하는 용어의 뜻은 제1항에서 규정하는 것을 제외하고는 「소방기본법」, 「화재의 예방 및 안전관리에 관한 법률」, 「소방시설공사업법」, 「위험물안전관리법」 및 「건축법」에서 정하는 바에 따른다.`;
const NFPC = `제3조(정의) 이 기준에서 사용하는 용어의 정의는 다음과 같다.
1. "고가수조"란 구조물 또는 지형지물 등에 설치하여 자연낙차의 압력으로 급수하는 수조를 말한다.
4. "정격토출량"이란 펌프의 정격부하운전 시 토출량으로서 정격토출압력에서의 토출량을 말한다.
22. "분기배관"이란 배관 측면에 구멍을 뚫어 둘 이상의 관로가 생기도록 가공한 배관으로서 다음 각 목의 분기배관을 말한다.
가. "확관형 분기배관"이란 배관의 측면에 조그만 구멍을 뚫고 소성가공으로 확관시켜 배관 용접이음자리를 만들거나 배관 용접이음자리에 배관이음쇠를 용접 이음한 배관을 말한다.
나. "비확관형 분기배관"이란 배관의 측면에 분기호칭내경 이상의 구멍을 뚫고 배관이음쇠를 용접 이음한 배관을 말한다.
28. "반사판(디플렉터)"이란 스프링클러헤드의 방수구에서 유출되는 물을 세분시키는 작용을 하는 것을 말한다.`;

test("법률 정의 — 항·호 출처, 딸린 목은 같은 정의에 포함", () => {
  const d = parseDefArticle("제2조(정의)", FIRE);
  expect(d.map((x) => x.term)).toEqual(["소방시설", "소방시설등", "화재안전기준", "소방용품"]);
  expect(d[0].ref).toBe("제2조제1항제1호");
  const k = d.find((x) => x.term === "화재안전기준");
  expect(k.ref).toBe("제2조제1항제6호");
  expect(k.text).toMatch(/\n가\. 성능기준/);
  expect(k.text).toMatch(/\n나\. 기술기준/);
  expect(d[0].text).toBe('"소방시설"이란 소화설비, 경보설비, 피난구조설비, 소화용수설비, 그 밖에 소화활동설비로서 대통령령으로 정하는 것을 말한다.');
});

test("화재안전성능기준 정의 — 항 없는 조문, 목 안의 정의도 따로, 괄호 든 용어", () => {
  const d = parseDefArticle("제3조(정의)", NFPC);
  expect(d.map((x) => [x.term, x.ref])).toEqual([
    ["고가수조", "제3조제1호"],
    ["정격토출량", "제3조제4호"],
    ["분기배관", "제3조제22호"],
    ["확관형 분기배관", "제3조제22호가목"],
    ["비확관형 분기배관", "제3조제22호나목"],
    ["반사판(디플렉터)", "제3조제28호"],
  ]);
  expect(d[2].text.split("\n")).toHaveLength(3);
});

test("한자 병기·의 번호·삭제·항 하나짜리 정의", () => {
  const d = parseDefArticle("제2조(정의)", `제2조(정의) 이 영에서 사용하는 용어의 뜻은 다음과 같다.
1. "무창층"(無窓層)이란 지상층 중 다음 각 목의 요건을 모두 갖춘 개구부의 면적의 합계가 해당 층의 바닥면적의 30분의 1 이하가 되는 층을 말한다.
가. 크기는 지름 50센티미터 이상의 원이 통과할 수 있을 것
2. 삭제 <2020. 1. 1.>
3의2. "피난층"이란 곧바로 지상으로 갈 수 있는 출입구가 있는 층을 말한다.`);
  expect(d.map((x) => [x.term, x.alias, x.ref])).toEqual([
    ["무창층", "無窓層", "제2조제1호"],
    ["피난층", "", "제2조제3의2호"],
  ]);
  const one = parseDefArticle("제2조(정의)", `제2조(정의)\n① 이 법에서 "다중이용업"이란 불특정 다수인이 이용하는 영업을 말한다.\n② 다른 말은 따른다.`);
  expect(one).toEqual([{ term: "다중이용업", alias: "", text: '"다중이용업"이란 불특정 다수인이 이용하는 영업을 말한다.', ref: "제2조제1항" }]);
});

test("서버 응답 → 목록·출처, 검색 순서", () => {
  const fam = defsFromFam({ items: [{ kind: "law", ver: { name: "소방시설 설치 및 관리에 관한 법률", eff: "20241201" }, link: "L", arts: [{ label: "제2조(정의)", text: FIRE }] }, { kind: "rule", error: "현행 법령 없음" }] }, "소방시설법");
  expect(fam[0]).toMatchObject({ term: "소방시설", src: "소방시설 설치 및 관리에 관한 법률 제2조제1항제1호", group: "소방시설법", kind: "law", link: "L" });
  const std = defsFromStd({ items: [{ std: "103", ver: { name: "스프링클러설비의 화재안전성능기준(NFPC 103)", eff: "20260301" }, link: "S", arts: [{ label: "제3조(정의)", text: NFPC }] }, { std: "999", error: "x" }] });
  expect(std).toHaveLength(6);
  const all = [...fam, ...std];
  expect(searchDefs(all, "소방시설").map((x) => x.term).slice(0, 2)).toEqual(["소방시설", "소방시설등"]);
  expect(searchDefs(all, "분기 배관").map((x) => x.term)).toEqual(["분기배관", "확관형 분기배관", "비확관형 분기배관"]);
  expect(searchDefs(all, "디플렉터").map((x) => x.term)).toEqual(["반사판(디플렉터)"]);
  expect(searchDefs(all, "소성가공")).toHaveLength(0);
  expect(searchDefs(all, "소성가공", { body: true }).map((x) => x.term)).toEqual(["분기배관", "확관형 분기배관"]); // 본문 검색(목 포함)
  expect(searchDefs(all, "", { group: "화재안전성능기준" })).toHaveLength(6);
});
